import { describe, expect, it } from 'vitest';
import { BANGDB, MSSQL, MYSQL, POSTGRES, SQLITE, dialectOf, identityOf, viewSelect } from './dialect';
import { changeStatements, columnDefSql, createTableSql, insertBatchSql, insertModes, pageSql, toScript } from './goapi';
import { normalize } from '../store/store';

const base = { table_name: 't', table_type: 'NORMAL_TABLE', key_type: 'NORMAL_KEY', key_sz: 0, allow_duplicate: false, allow_rev_idx: false, version_type: 0 } as const;

describe('dialects', () => {
  it('quote identifiers and schema-qualified tables', () => {
    expect(POSTGRES.qt('sales.orders')).toBe('"sales"."orders"');
    expect(MSSQL.qt('dbo2.t')).toBe('[dbo2].[t]');
    expect(MYSQL.qt('a`b')).toBe('`a``b`');
    expect(BANGDB.qt('a.b')).toBe('"a.b"');
  });
  it('page with LIMIT/OFFSET or OFFSET/FETCH', () => {
    expect(pageSql('t', { limit: 10, offset: 20 }, { kind: 'pk', columns: ['id'] }, MYSQL)).toBe('SELECT * FROM `t` ORDER BY `id` LIMIT 10 OFFSET 20');
    expect(pageSql('t', { limit: 10, offset: 0 }, null, MSSQL)).toBe('SELECT * FROM [t] ORDER BY (SELECT NULL) OFFSET 0 ROWS FETCH NEXT 10 ROWS ONLY');
    expect(pageSql('t', { limit: 5, offset: 0, orderBy: 'a', desc: true }, { kind: 'ctid' }, POSTGRES)).toBe('SELECT ctid::text AS "__rowid", * FROM "t" ORDER BY "a" DESC LIMIT 5 OFFSET 0');
  });
  it('auto increment per database', () => {
    const id = { name: 'id', decl: 'INT', pk: true, autoinc: true };
    expect(columnDefSql(id, {}, MYSQL)).toBe('`id` INT AUTO_INCREMENT PRIMARY KEY');
    expect(columnDefSql(id, {}, MSSQL)).toBe('[id] INT IDENTITY(1,1) PRIMARY KEY');
    expect(columnDefSql({ ...id, decl: 'integer' }, {}, POSTGRES)).toBe('"id" integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
    expect(columnDefSql({ ...id, decl: 'INTEGER' }, {}, SQLITE)).toBe('"id" INTEGER PRIMARY KEY AUTOINCREMENT');
  });
  it('ADD COLUMN clauses follow what each database accepts', () => {
    const c = { name: 'c', decl: 'INT', unique: true, check: 'c > 0', refTable: 'p' };
    expect(columnDefSql(c, { inTable: false }, POSTGRES)).toBe('"c" INT UNIQUE CHECK (c > 0) REFERENCES "p"');
    expect(columnDefSql(c, { inTable: false }, SQLITE)).toBe('"c" INT CHECK (c > 0) REFERENCES "p"');
    expect(columnDefSql(c, { inTable: false }, BANGDB)).toBe('"c" INT');
  });
  it('storage options only for BangDB; no IF NOT EXISTS on SQL Server', () => {
    const spec = { ...base, ifNotExists: true, storage: { using: 'memory' as const }, columns: [{ name: 'a', decl: 'INT' }] };
    expect(createTableSql(spec, MSSQL)).toBe('CREATE TABLE [t] (\n  [a] INT\n)');
    expect(createTableSql(spec, BANGDB)).toBe('CREATE TABLE IF NOT EXISTS "t" (\n  "a" INT\n) USING memory');
  });
  it('literals', () => {
    expect(POSTGRES.literal(true)).toBe('TRUE');
    expect(POSTGRES.literal({ blob: 'QUI=' })).toBe("'\\x4142'::bytea");
    expect(MSSQL.literal("it's")).toBe("N'it''s'");
    expect(MSSQL.literal({ blob: 'QUI=' })).toBe('0x4142');
    expect(MYSQL.literal('a\\b')).toBe("'a\\\\b'");
  });
  it('bulk insert duplicate handling', () => {
    expect(insertModes(MSSQL)).toEqual(['insert']);
    expect(insertBatchSql('t', ['a'], [[1]], 'ignore', POSTGRES).sql).toBe('INSERT INTO "t" ("a") VALUES (?) ON CONFLICT DO NOTHING');
    expect(insertBatchSql('t', ['a'], [[1]], 'replace', MYSQL).sql).toBe('REPLACE INTO `t` (`a`) VALUES (?)');
    expect(() => insertBatchSql('t', ['a'], [[1]], 'replace', POSTGRES)).toThrow();
  });
  it('view SELECT out of each definition style', () => {
    expect(viewSelect('CREATE ALGORITHM=UNDEFINED DEFINER=`root`@`%` SQL SECURITY DEFINER VIEW `v` AS select 1 AS `a`;')).toBe('select 1 AS `a`');
    expect(viewSelect('CREATE VIEW "s"."v" (a, b) AS\nSELECT 1, 2')).toBe('SELECT 1, 2');
    expect(viewSelect('CREATE VIEW payroll AS SELECT d.name FROM dept d;')).toBe('SELECT d.name FROM dept d');
  });
});

describe('row identity and changes', () => {
  it('rowid, ctid, primary key or none', () => {
    const t = { name: 't', kind: 'table' as const, columns: [{ name: 'id', pk: true }] };
    expect(identityOf(BANGDB, { ...t, columns: [] })).toEqual({ kind: 'rowid', expr: 'rowid' });
    expect(identityOf(SQLITE, { ...t, rowid: 'rowid' })).toEqual({ kind: 'rowid', expr: 'rowid' });
    expect(identityOf(POSTGRES, { ...t, rowid: 'ctid' })).toEqual({ kind: 'pk', columns: ['id'] });
    expect(identityOf(POSTGRES, { ...t, columns: [], rowid: 'ctid' })).toEqual({ kind: 'ctid' });
    expect(identityOf(MYSQL, { ...t, columns: [] })).toBeNull();
    expect(identityOf(MYSQL, { ...t, kind: 'view' })).toBeNull();
  });
  it('builds statements by primary key or ctid', () => {
    expect(changeStatements('t', [{ kind: 'update', pk: { id: 1, k: 'a' }, values: { x: 2 } }, { kind: 'delete', pk: { id: 3, k: 'b' } }], MYSQL, { kind: 'pk', columns: ['id', 'k'] })).toEqual([
      { sql: 'UPDATE `t` SET `x` = ? WHERE `id` = ? AND `k` = ?', args: [2, 1, 'a'] },
      { sql: 'DELETE FROM `t` WHERE `id` = ? AND `k` = ?', args: [3, 'b'] }
    ]);
    expect(changeStatements('t', [{ kind: 'delete', rowid: '(0,3)' }], POSTGRES, { kind: 'ctid' })).toEqual([{ sql: 'DELETE FROM "t" WHERE ctid = ?::tid', args: ['(0,3)'] }]);
  });
  it('BangDB scripts renumber ? outside quotes', () => {
    expect(toScript([{ sql: "UPDATE \"t?\" SET a = ? WHERE b = '?'", args: [1] }, { sql: 'DELETE FROM t WHERE id = ?', args: [2] }]))
      .toEqual({ sql: "BEGIN;\nUPDATE \"t?\" SET a = ?1 WHERE b = '?';\nDELETE FROM t WHERE id = ?2;\nCOMMIT;", args: [1, 2] });
  });
});

describe('gateway connections', () => {
  it('normalize keeps database settings and the default database', () => {
    const c = normalize({ kind: 'postgres', db: { host: 'h', port: 0 as unknown as number, database: 'app' } });
    expect(c.kind).toBe('postgres');
    expect(c.db).toEqual({ host: 'h', database: 'app' });
    expect(c.defaultDb).toBe('app');
    expect(c.baseUrl).toBe('');
    expect(normalize({ kind: 'sqlite', db: { file: 'a.db' } }).defaultDb).toBe('main');
    expect(normalize({ kind: 'redis', db: { host: 'h' } }).defaultDb).toBe('0');
    expect(dialectOf(normalize({ kind: 'mssql', db: {} })).id).toBe('mssql');
  });
});
